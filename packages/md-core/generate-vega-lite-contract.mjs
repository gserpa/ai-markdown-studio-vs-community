import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';

const directory = path.dirname(fileURLToPath(import.meta.url));
const previewRequire = createRequire(path.resolve(directory, '../md-preview-web/package.json'));
const packageDirectory = path.dirname(path.dirname(previewRequire.resolve('vega-lite')));
const schemaPath = path.join(packageDirectory, 'build/vega-lite-schema.json');
const schemaSource = await readFile(schemaPath, 'utf8');
const schema = JSON.parse(schemaSource);
const packageInfo = JSON.parse(await readFile(path.join(packageDirectory, 'package.json'), 'utf8'));
const rootSchema = { $ref: '#/definitions/TopLevelSpec' };

// Keep native marks and composition grammar, omitting disallowed configuration
// and documentation payloads. Property dictionaries preserve their literal keys.
function strip(value, dictionary = false) {
  if (Array.isArray(value)) return value.map(item => strip(item));
  if (!value || typeof value !== 'object') return value;
  const result = Object.fromEntries(Object.entries(value)
    .filter(([key]) => dictionary || !['description', 'default', 'examples', '$comment'].includes(key))
    .map(([key, item]) => [key, strip(item, ['properties', 'definitions', '$defs', 'patternProperties'].includes(key))]));
  if (result.properties) for (const key of ['config', 'params', 'transform', 'datasets', 'selection']) delete result.properties[key];
  return result;
}
const definitions = {};
function visit(value) {
  if (!value || typeof value !== 'object') return;
  if (typeof value.$ref === 'string') {
    const name = decodeURIComponent(value.$ref.replace('#/definitions/', ''));
    if (!(name in definitions)) {
      definitions[name] = strip(schema.definitions[name]);
      visit(definitions[name]);
    }
  }
  for (const child of Object.values(value)) visit(child);
}
const nativeSchema = strip(rootSchema);
visit(nativeSchema);
const compiler = new Ajv({ strict: false, allErrors: false, inlineRefs: false, code: { source: true, esm: true }, logger: false });
const validate = compiler.compile({ ...nativeSchema, definitions });
const compiled = standaloneCode(compiler, validate);
const bundled = await build({
  stdin: { contents: compiled, resolveDir: directory, sourcefile: 'native-vega-lite-validator.mjs' },
  bundle: true, platform: 'neutral', format: 'cjs', minify: true, write: false,
});
const marks = [...schema.definitions.Mark.enum, ...schema.definitions.CompositeMark.anyOf.map(ref => {
  const definition = schema.definitions[ref.$ref.split('/').at(-1)];
  return definition.const ?? definition.enum?.[0];
})].sort();
const compositions = [...new Set(schema.definitions.TopLevelSpec.anyOf.flatMap(ref => {
  const definition = schema.definitions[ref.$ref.split('/').at(-1)];
  return (definition.required ?? []).filter(key => ['layer', 'facet', 'repeat', 'concat', 'hconcat', 'vconcat'].includes(key));
}))].sort();
if (marks.some(mark => typeof mark !== 'string')) throw new Error('Cannot extract the installed native mark inventory.');
const ajvRequire = createRequire(import.meta.url);
const ajvDirectory = path.dirname(ajvRequire.resolve('ajv/package.json'));
const license = await readFile(path.join(ajvDirectory, 'LICENSE'), 'utf8');
const schemaLicense = await readFile(path.join(packageDirectory, 'LICENSE'), 'utf8');
const header = '// Generated by generate-vega-lite-contract.mjs; do not edit.\n';
const notice = '/*! Includes precompiled Ajv runtime helpers.\n' + license + '\nVega-Lite schema attribution:\n' + schemaLicense + '\n*/\n';
const schemaHash = createHash('sha256').update(schemaSource).digest('hex');
const metadata = '\nmodule.exports.VEGA_LITE_SCHEMA_VERSION = ' + JSON.stringify(packageInfo.version) + ';\n'
  + 'module.exports.VEGA_LITE_SCHEMA_HASH = ' + JSON.stringify(schemaHash) + ';\n'
  + 'module.exports.VEGA_LITE_MARKS = ' + JSON.stringify(marks) + ';\n';
const compositionMetadata = 'module.exports.VEGA_LITE_COMPOSITIONS = ' + JSON.stringify(compositions) + ';\n';
const output = header + notice + bundled.outputFiles[0].text + metadata + compositionMetadata;
const target = path.join(directory, 'src/visualizations/vegaLiteNativeValidator.cjs');
const declaration = header + 'declare const validate: { (value: unknown): boolean; errors?: Array<{ instancePath: string; message?: string }> };\nexport default validate;\nexport { validate };\n'
  + 'export declare const VEGA_LITE_SCHEMA_VERSION: ' + JSON.stringify(packageInfo.version) + ';\n'
  + 'export declare const VEGA_LITE_SCHEMA_HASH: ' + JSON.stringify(schemaHash) + ';\n'
  + 'export declare const VEGA_LITE_MARKS: readonly ' + JSON.stringify(marks) + ';\n'
  + 'export declare const VEGA_LITE_COMPOSITIONS: readonly ' + JSON.stringify(compositions) + ';\n';
const declarationPath = target.replace(/\.cjs$/u, '.d.cts');
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')).replace(/\r\n/gu, '\n') !== output) throw new Error('The native Vega-Lite validator is stale. Run npm run generate:vega-lite --workspace=packages/md-core.');
  if ((await readFile(declarationPath, 'utf8')).replace(/\r\n/gu, '\n') !== declaration) throw new Error('The native validator types are stale.');
} else {
  await writeFile(target, output);
  await writeFile(declarationPath, declaration);
}
console.log('Vega-Lite ' + packageInfo.version + ': ' + marks.length + ' marks, ' + output.length + ' generated bytes.');
