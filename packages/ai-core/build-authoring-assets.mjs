import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createFeatureAuthoringReference } from './dist/featureAuthoring.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const reference = '# Markdown AI Studio feature selection and authoring\n\n<!-- Generated by packages/ai-core/build-authoring-assets.mjs. -->\n\n' + createFeatureAuthoringReference() + '\n';
for (const skill of ['markdown-ai-studio-document', 'markdown-ai-studio-presentation', 'markdown-ai-studio-presentation-copilot']) {
  const directory = path.join(root, 'apps/ai-markdown-studio-vs-community/skills', skill, 'references');
  const target = path.join(directory, 'visualizations.md');
  if (existsSync(target) && readFileSync(target, 'utf8').replace(/\r\n/g, '\n') === reference) continue;
  mkdirSync(directory, { recursive: true });
  writeFileSync(target, reference, 'utf8');
}
