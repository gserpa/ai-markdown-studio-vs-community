import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createVisualizationAuthoringInstructions } from './dist/visualizationAuthoring.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const reference = '# Visualization authoring\n\n<!-- Generated by packages/ai-core/build-authoring-assets.mjs. -->\n\n' + createVisualizationAuthoringInstructions() + '\n';
for (const skill of ['markdown-ai-studio-presentation', 'markdown-ai-studio-presentation-copilot']) {
  const directory = path.join(root, 'apps/ai-markdown-studio-vs-community/skills', skill, 'references');
  mkdirSync(directory, { recursive: true });
  writeFileSync(path.join(directory, 'visualizations.md'), reference, 'utf8');
}
